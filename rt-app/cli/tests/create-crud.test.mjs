const project=fileURLToPath(new URL('../../../',import.meta.url));
const spec={name:'products',title:'Products',fields:[{name:'name',type:'string'},{name:'price',type:'number'},{name:'active',type:'boolean'}],actions:['publish']};
async function fixture(t){
  const base=join(project,'.rt-app');await mkdir(base,{recursive:true});const root=await mkdtemp(join(base,'crud-test-'));
  t.after(()=>rm(root,{recursive:true,force:true}));await mkdir(join(root,'packages'));
  await writeFile(join(root,'package.json'),JSON.stringify({type:'module',private:true,workspaces:['packages/*'],rtApp:{}}));
  await writeFile(join(root,'modules.json'),JSON.stringify({modules:['content','infra','users','auth','acl']}));
  for(const [file,content] of Object.entries(registries([])))await writeFile(join(root,file),content);
  return root;
}
test('generator validates names, previews without writes and refuses overwrite/custom registry edits',async t=>{
  const root=await fixture(t);
  for(const name of ['../escape','auth','x;exit','__proto__'])assert.throws(()=>normalize({...spec,name}));
  assert.throws(()=>normalize({...spec,fields:[{name:'version',type:'number'}]}));
  const before=await readFile(join(root,'modules.json'),'utf8');
  assert.equal((await generate(root,spec,{dryRun:true})).dryRun,true);
  assert.equal(await readFile(join(root,'modules.json'),'utf8'),before);
  await assert.rejects(access(join(root,'packages/products')));
  await generate(root,spec);await assert.rejects(generate(root,spec),/already/);
  const cli=spawnSync(process.execPath,[fileURLToPath(new URL('../bin/rta.mjs',import.meta.url)),'create','crud','orders','--fields','title:string,paid:boolean?','--json'],{cwd:root,encoding:'utf8'});
  assert.equal(cli.status,0,cli.stderr);assert.equal(JSON.parse(cli.stdout).created,'packages/orders');
  assert.deepEqual(JSON.parse(await readFile(join(root,'modules.json'),'utf8')).generatedCrud.map(e=>e.name),['products','orders']);
  await writeFile(join(root,'packages/admin.js'),'// user edits');
  await assert.rejects(generate(root,{...spec,name:'invoices'}),/custom edits/);
  const result=spawnSync(process.execPath,[fileURLToPath(new URL('../bin/rta.mjs',import.meta.url)),'create','crud','../invalid','--json'],{cwd:root,encoding:'utf8'});
  assert.equal(result.status,1);
});
