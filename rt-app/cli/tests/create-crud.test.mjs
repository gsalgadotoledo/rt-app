test('generated search traverses empty pages and preserves continuation bounds',async t=>{
  const root=await fixture(t);await generate(root,spec);
  const {search}=await import(pathToFileURL(join(root,'packages/products/src/search.js')));
  let calls=0;const store={list:async()=>({items:[{data:{name:++calls===3?'needle':'other'}}],cursor:String(calls)})};
  const page=await search(store,'pk',{q:'needle'},spec.fields,r=>r.data);assert.equal(calls,3);assert.equal(page.items[0].name,'needle');assert.equal(page.cursor,'3');
  calls=0;const empty=await search(store,'pk',{q:'missing'},spec.fields,r=>r.data);assert.equal(calls,10);assert.equal(empty.cursor,'10');
});
